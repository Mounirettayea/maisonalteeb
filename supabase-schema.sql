-- MAISON AL TEEB — Supabase schema / security baseline
-- Idempotent baseline for the storefront, staff profiles and product media.
-- This file does not create or modify the separate POS/booking applications that may share this project.

create schema if not exists private;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  name_fr text,
  name_en text,
  category text not null,
  gender text default 'للجنسين',
  size text,
  price numeric(12,2) not null default 0,
  old_price numeric(12,2) not null default 0,
  discount integer not null default 0,
  image text,
  image_url text,
  images text[] not null default '{}'::text[],
  video_url text,
  is_best_seller boolean not null default false,
  description text,
  active boolean not null default true,
  stock integer not null default 0,
  low_stock_threshold integer not null default 5,
  barcode text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.products add column if not exists image text;
alter table public.products add column if not exists image_url text;
alter table public.products add column if not exists images text[] not null default '{}'::text[];
alter table public.products add column if not exists video_url text;
alter table public.products add column if not exists stock integer not null default 0;
alter table public.products add column if not exists low_stock_threshold integer not null default 5;
alter table public.products add column if not exists barcode text;
alter table public.products add column if not exists updated_at timestamptz not null default now();

update public.products set image = image_url where image is null and image_url is not null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'products_images_max_six' and conrelid = 'public.products'::regclass) then
    alter table public.products add constraint products_images_max_six check (cardinality(images) <= 6);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'products_stock_nonnegative' and conrelid = 'public.products'::regclass) then
    alter table public.products add constraint products_stock_nonnegative check (stock >= 0);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'products_low_stock_threshold_nonnegative' and conrelid = 'public.products'::regclass) then
    alter table public.products add constraint products_low_stock_threshold_nonnegative check (low_stock_threshold >= 0);
  end if;
end
$$;

create unique index if not exists products_barcode_unique_idx
  on public.products (barcode)
  where barcode is not null and btrim(barcode) <> '';
create index if not exists products_active_id_idx on public.products (active, id);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'cashier' check (role in ('admin','manager','cashier')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles add column if not exists full_name text;
alter table public.profiles add column if not exists updated_at timestamptz not null default now();

create or replace function private.has_role(required_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = any(required_roles)
  );
$$;

grant usage on schema private to authenticated;
revoke all on function private.has_role(text[]) from public, anon;
grant execute on function private.has_role(text[]) to authenticated;

alter table public.products enable row level security;
drop policy if exists "public read active products" on public.products;
drop policy if exists "public can read active products" on public.products;
create policy "public read active products" on public.products for select to anon, authenticated using (active = true);

drop policy if exists "staff can read all products" on public.products;
create policy "staff can read all products" on public.products for select to authenticated
  using (private.has_role(array['admin','manager','cashier']::text[]));

drop policy if exists "managers can insert products" on public.products;
create policy "managers can insert products" on public.products for insert to authenticated
  with check (private.has_role(array['admin','manager']::text[]));

drop policy if exists "managers can update products" on public.products;
create policy "managers can update products" on public.products for update to authenticated
  using (private.has_role(array['admin','manager']::text[]))
  with check (private.has_role(array['admin','manager']::text[]));

drop policy if exists "admins can delete products" on public.products;
create policy "admins can delete products" on public.products for delete to authenticated
  using (private.has_role(array['admin']::text[]));

alter table public.profiles enable row level security;
drop policy if exists "users can read own profile" on public.profiles;
create policy "users can read own profile" on public.profiles for select to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "admins can manage profiles" on public.profiles;
create policy "admins can manage profiles" on public.profiles for update to authenticated
  using (private.has_role(array['admin']::text[]))
  with check (private.has_role(array['admin']::text[]));

grant usage on schema public to anon, authenticated;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant select, update on public.profiles to authenticated;

do $$
begin
  if to_regclass('public.products_id_seq') is not null then
    execute 'grant usage, select on sequence public.products_id_seq to authenticated';
  end if;
end
$$;

insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do update set
  public = true,
  file_size_limit = 104857600,
  allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif','image/avif','video/mp4','video/webm','video/quicktime'];

drop policy if exists "public read product images" on storage.objects;
create policy "public read product images" on storage.objects for select to anon, authenticated
  using (bucket_id = 'product-images');

drop policy if exists "managers upload product images" on storage.objects;
create policy "managers upload product images" on storage.objects for insert to authenticated
  with check (bucket_id = 'product-images' and private.has_role(array['admin','manager']::text[]));

drop policy if exists "managers update product images" on storage.objects;
create policy "managers update product images" on storage.objects for update to authenticated
  using (bucket_id = 'product-images' and private.has_role(array['admin','manager']::text[]))
  with check (bucket_id = 'product-images' and private.has_role(array['admin','manager']::text[]));

drop policy if exists "admins delete product images" on storage.objects;
create policy "admins delete product images" on storage.objects for delete to authenticated
  using (bucket_id = 'product-images' and private.has_role(array['admin']::text[]));

